#!/usr/bin/env bash
# 把 billion-context/kernel 的官方 ESM 产物重新打成 goja 可执行的 CJS(ES2017)，
# 并把上游版本号 + bundle 指纹写进 internal/kernel/version_gen.go。
set -euo pipefail
KERNEL=${KERNEL:-/tmp/billion-context/kernel}
OUT=${OUT:-./internal/kernel}

# 先把版本读出来（fail fast）：node 不可用/路径不对时，绝不能先把 bundle 覆盖成半成品。
command -v node >/dev/null 2>&1 || { echo "需要 node（读上游 package.json / 计算 bundle 指纹）" >&2; exit 1; }
# 用 argv 传路径，避开 Windows 路径反斜杠在 JS 字符串里被当转义。
VERSION=$(node -e "process.stdout.write(JSON.parse(require('fs').readFileSync(process.argv[1],'utf8')).version)" "$KERNEL/package.json")
[ -f "$KERNEL/dist/index.js" ] || { echo "找不到 $KERNEL/dist/index.js，先在上游 kernel 目录跑 npm run build" >&2; exit 1; }
mkdir -p "$OUT"

# esbuild 的 .bin shim 在部分环境（纯 Windows、无 bash 的 node_modules）不可执行，
# 有 node 就直接调它的 JS 入口。
if [ -f "$KERNEL/node_modules/esbuild/bin/esbuild" ]; then
  ESBUILD=(node "$KERNEL/node_modules/esbuild/bin/esbuild")
else
  ESBUILD=("$KERNEL/node_modules/.bin/esbuild")
fi

"${ESBUILD[@]}" "$KERNEL/dist/index.js" \
  --bundle --format=cjs --platform=neutral --target=es2017 \
  --external:crypto --external:path --external:fs --external:module --external:node:* \
  --define:import.meta.url='"file:///kernel/index.js"' \
  --outfile="$OUT/kernel.dist.cjs"

# 产物指纹：TestBundleDigest 用它确认「仓库里的 bundle 就是脚本打出来的那份」，
# 换过 bundle 却没重跑脚本会立刻红。
DIGEST=$(node -e "process.stdout.write(require('crypto').createHash('sha256').update(require('fs').readFileSync(process.argv[1])).digest('hex'))" "$OUT/kernel.dist.cjs")
ESBUILD_VERSION=$("${ESBUILD[@]}" --version)

cat > "$OUT/version_gen.go" <<EOF
// Code generated by script/build-cjs.sh from the upstream kernel/package.json. DO NOT EDIT.

package kernel

// BundleVersion 是 go:embed 的 kernel.dist.cjs 对应的上游 acp-kernel 版本。
//
// 上游 index.ts 既不导出 KERNEL_VERSION 也不导出 version，所以版本号只能由
// 重打包脚本从上游 package.json 抄过来写死；换 bundle 时重跑脚本即可。
const BundleVersion = "$VERSION"

// BundleDigest 是 kernel.dist.cjs 的 sha256（小写十六进制），
// 由同一个脚本算出；TestBundleDigest 拿它对嵌入内容做校验。
const BundleDigest = "$DIGEST"

// BundleEsbuild 是打这份 bundle 用的 esbuild 版本（审计用：不同版本可能产出不同字节）。
const BundleEsbuild = "$ESBUILD_VERSION"
EOF

echo "kernel.dist.cjs <= acp-kernel $VERSION (sha256 ${DIGEST:0:16}…, esbuild $ESBUILD_VERSION)"
